import { useState, useEffect } from 'react';
import { useParams } from 'react-router-dom';
import { motion } from 'framer-motion';
import { Sparkles, Calendar, User, Building2 } from 'lucide-react';
import { guidesAPI } from '../services/api';
import GuideViewer from '../components/guides/GuideViewer';
import LoadingSpinner from '../components/ui/LoadingSpinner';

const SharedGuide = () => {
  const { slug } = useParams();
  const [guide, setGuide] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');

  useEffect(() => {
    const fetchGuide = async () => {
      try {
        const res = await guidesAPI.getShared(slug);
        setGuide(res.data.guide);
      } catch (err) {
        setError('This guide is not available or has been made private.');
      } finally {
        setLoading(false);
      }
    };
    fetchGuide();
  }, [slug]);

  if (loading) {
    return (
      <div className="min-h-screen bg-surface-950 flex items-center justify-center">
        <LoadingSpinner text="Loading shared guide..." />
      </div>
    );
  }

  if (error) {
    return (
      <div className="min-h-screen bg-surface-950 flex items-center justify-center">
        <div className="glass-card p-12 text-center max-w-md">
          <Sparkles size={48} className="text-surface-700 mx-auto mb-4" />
          <h2 className="text-xl font-bold text-white mb-2">Guide Not Found</h2>
          <p className="text-surface-400">{error}</p>
        </div>
      </div>
    );
  }

  return (
    <div className="min-h-screen bg-surface-950">
      {/* Top Bar */}
      <div className="bg-surface-900/80 backdrop-blur-xl border-b border-surface-800/50 py-3">
        <div className="max-w-4xl mx-auto px-4 flex items-center justify-between">
          <div className="flex items-center gap-2">
            <img
              src="/onboard logo.jpeg"
              alt="OnboardAI Logo"
              className="w-7 h-7 rounded-lg shadow-md object-cover"
            />
            <span className="font-bold gradient-text text-sm">OnboardAI</span>
          </div>
          <span className="text-xs text-surface-500">Shared Guide</span>
        </div>
      </div>

      <div className="max-w-4xl mx-auto px-4 py-8">
        {/* Header */}
        <motion.div
          initial={{ opacity: 0, y: 20 }}
          animate={{ opacity: 1, y: 0 }}
          className="glass-card p-6 mb-6"
        >
          <h1 className="text-2xl font-bold text-white mb-3">{guide.title}</h1>
          <div className="flex flex-wrap items-center gap-4 text-sm text-surface-400">
            {guide.userId?.name && (
              <span className="flex items-center gap-1.5">
                <User size={14} /> {guide.userId.name}
              </span>
            )}
            {guide.userId?.companyName && (
              <span className="flex items-center gap-1.5">
                <Building2 size={14} /> {guide.userId.companyName}
              </span>
            )}
            <span className="flex items-center gap-1.5">
              <Calendar size={14} /> {new Date(guide.createdAt).toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric' })}
            </span>
          </div>
        </motion.div>

        {/* Content */}
        <motion.div
          initial={{ opacity: 0, y: 20 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ delay: 0.1 }}
          className="glass-card p-8"
        >
          <GuideViewer content={guide.content} />
        </motion.div>

        {/* Footer */}
        <div className="text-center mt-8 text-xs text-surface-600">
          Generated by <span className="gradient-text font-semibold">OnboardAI</span> — AI-Powered Onboarding Guide Generator
        </div>
      </div>
    </div>
  );
};

export default SharedGuide;
